def seed_munkanemek(db: Session) -> None:
    existing = {m.kod: m for m in db.query(Munkanem).all()}
    for item in _MUNKANEM_SEED:
        row = existing.get(item["kod"])
        if row is None:
            db.add(Munkanem(**item))
        else:
            for field, value in item.items():
                if field != "kod":
                    setattr(row, field, value)
    db.commit()


def seed_torzsadatok(db: Session) -> None:
    existing = {(t.tipus, t.ertek) for t in db.query(Torzsadat.tipus, Torzsadat.ertek).all()}
    for tipus, ertek in _TORZSADAT_SEED:
        if (tipus, ertek) not in existing:
            db.add(Torzsadat(tipus=tipus, ertek=ertek))
    db.commit()


def seed_szemelyek(db: Session) -> None:
    existing_names = {s.nev for s in db.query(Szemely.nev).all()}
    for item in _SZEMELY_SEED:
        if item["nev"] not in existing_names:
            db.add(Szemely(**item))
    db.commit()


def seed_admin(db: Session) -> None:
    admin = db.query(User).filter(User.username == "admin").first()
    password = settings.admin_password
    if not admin:
        if not password:
            password = secrets.token_urlsafe(16)
            logger.warning(
                "ADMIN_PASSWORD not set — generated random admin password: %s "
                "(set ADMIN_PASSWORD in your environment to control this)",
                password,
            )
        admin = User(
            username="admin",
            email="admin@ubrankovics.local",
            full_name="Rendszergazda",
            hashed_password=hash_password(password),
            role=UserRole.ADMIN,
        )
        db.add(admin)
        db.commit()
    elif password:
        admin.hashed_password = hash_password(password)
        db.commit()
